/**
 * Helper for default annual pricing behavior:
 * monthly × 12 × 0.83, then rounded to nearest amount ending in .99.
 */
export function calculateAnnualPriceFromMonthly(monthlyPrice: number): number {
  const discounted = monthlyPrice * 12 * 0.83;
  const nearestDollar = Math.round(discounted);
  return Number(`${nearestDollar - 1}.99`);
}

